    public static void checkProtocolVersion(String remoteVersion) {
        if (!PROTOCOL_VERSION.equals(remoteVersion)) {
            AntigravityMod.LOGGER.warn("Network protocol mismatch! Local: " + PROTOCOL_VERSION + ", Remote: " + remoteVersion);
        } else {
            AntigravityMod.LOGGER.info("Network protocol match: " + PROTOCOL_VERSION);
        }
    }
    
    public static int getPacketCount() {
        return id;
    }
    
    public static String getProtocolVersion() {
        return PROTOCOL_VERSION;
    }
    
