    /**
     * Monitors network traffic on the channel.
     * Can be used to detect packet spam or heavy load.
     */
    public static class NetworkTrafficMonitor {
        private static final java.util.Map<Class<?>, Integer> packetCounts = new java.util.HashMap<>();
        private static final java.util.Map<Class<?>, Long> byteCounts = new java.util.HashMap<>();
        
        public static void recordPacket(Class<?> list, int bytes) {
            packetCounts.merge(list, 1, Integer::sum);
            byteCounts.merge(list, (long)bytes, Long::sum);
        }
        
        public static void dumpStats() {
            AntigravityMod.LOGGER.info("=== Network Traffic Stats ===");
            packetCounts.forEach((k, v) -> {
                AntigravityMod.LOGGER.info("Packet: " + k.getSimpleName() + " | Count: " + v + " | Bytes: " + byteCounts.get(k));
            });
            AntigravityMod.LOGGER.info("=============================");
        }
        
        public static void clear() {
            packetCounts.clear();
            byteCounts.clear();
        }
        
        public static boolean isSpamming(Class<?> list) {
             return packetCounts.getOrDefault(list, 0) > 1000;
        }
    }
    
    /**
     * Logs exact packet history for debugging.
     * Stores last N packets.
     */
    public static class PacketHistory {
        private static final java.util.List<String> history = new java.util.ArrayList<>();
        private static final int MAX_HISTORY = 100;
        
        public static void log(String info) {
            history.add(java.time.Instant.now() + ": " + info);
            if (history.size() > MAX_HISTORY) {
                history.remove(0);
            }
        }
        
        public static void dump() {
             AntigravityMod.LOGGER.info("=== Packet History ===");
             for(String s : history) {
                 AntigravityMod.LOGGER.info(s);
             }
        }
    }
    
